"""Regenerate synthetic artwork test vectors (Python 3 + ImageMagick).

No Spotify artwork is included. PNGs are constructed with stdlib zlib; JPEG
and WebP encode a solid synthetic PPM with the locally installed ImageMagick.
The checked-in C header means tests need neither tool nor filesystem fixtures.
"""
from pathlib import Path
import struct
import subprocess
import tempfile
import zlib

ROOT = Path(__file__).resolve().parents[1]


def chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))


def png(width, height, body=True):
    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    result = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header)
    if body:
        row = b"\0" + bytes((32, 96, 160, 255)) * width
        result += chunk(b"IDAT", zlib.compress(row * height))
    return result + chunk(b"IEND", b"")


vectors = {"png": png(4, 2), "png_medium": png(128, 128), "png_max": png(256, 256),
           "budget_png": png(512, 512),
           "oversize_png": png(513, 1), "bomb_png": png(65535, 65535, False)}
with tempfile.TemporaryDirectory() as temporary:
    source = Path(temporary) / "solid.ppm"
    source.write_bytes(b"P6\n8 4\n255\n" + bytes((32, 96, 160)) * 32)
    for kind in ("jpeg", "webp"):
        target = Path(temporary) / ("solid." + kind)
        subprocess.run(["magick", str(source), "-strip", "-quality", "90", str(target)], check=True)
        vectors[kind] = target.read_bytes()
    source.write_bytes(b"P6\n256 256\n255\n" + bytes((32, 96, 160)) * (256 * 256))
    target = Path(temporary) / "solid-max.jpeg"
    subprocess.run(["magick", str(source), "-strip", "-sampling-factor", "2x2",
                    "-quality", "90", str(target)], check=True)
    vectors["jpeg_max"] = target.read_bytes()
    source.write_bytes(b"P6\n512 512\n255\n" + bytes((32, 96, 160)) * (512 * 512))
    target = Path(temporary) / "solid-max.webp"
    subprocess.run(["magick", str(source), "-strip", "-quality", "90", str(target)], check=True)
    vectors["webp_max"] = target.read_bytes()

lines = ["/* Generated by tools/artwork_fixtures.py; synthetic solid RGB(32,96,160). */",
         "#ifndef SPOTIC_ARTWORK_FIXTURES_H", "#define SPOTIC_ARTWORK_FIXTURES_H"]
for name, data in vectors.items():
    lines.append("static const unsigned char art_fixture_" + name + "[] = {")
    for offset in range(0, len(data), 16):
        lines.append("    " + ",".join(f"0x{value:02x}" for value in data[offset:offset + 16]) + ",")
    lines.append("};")
lines.append("#endif")
(ROOT / "tests/artwork_fixtures.h").write_text("\n".join(lines) + "\n", encoding="ascii")
