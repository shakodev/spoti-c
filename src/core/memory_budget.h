#ifndef SPOTIC_CORE_MEMORY_BUDGET_H
#define SPOTIC_CORE_MEMORY_BUDGET_H

#include <stddef.h>

/* Initial committed caps from docs/ROADMAP.md; reservations are not residency.
 * Shared pools are counted once. OS/driver allocations and stacks are separate.
 * Exceeding a cap must return an explicit failure, never grow a pool silently. */
#define MEMORY_KIB ((size_t)1024)
#define MEMORY_BUDGET_CORE (128 * MEMORY_KIB)
#define MEMORY_BUDGET_PROTOCOL (256 * MEMORY_KIB)
#define MEMORY_BUDGET_METADATA (256 * MEMORY_KIB)
#define MEMORY_BUDGET_HTTP (384 * MEMORY_KIB)
#define MEMORY_BUDGET_ENCRYPTED_BLOCKS (512 * MEMORY_KIB)
#define MEMORY_BUDGET_DECODERS (512 * MEMORY_KIB)
#define MEMORY_BUDGET_DECODE_SCRATCH (128 * MEMORY_KIB)
#define MEMORY_BUDGET_PCM (256 * MEMORY_KIB)
#define MEMORY_BUDGET_AUDIO_DEVICE (128 * MEMORY_KIB)
#define MEMORY_BUDGET_CLAY_AND_FRAME (1280 * MEMORY_KIB)
#define MEMORY_BUDGET_API_PAGES (1024 * MEMORY_KIB)
#define MEMORY_BUDGET_MODEL (512 * MEMORY_KIB)
#define MEMORY_BUDGET_UI_STATE (256 * MEMORY_KIB)
#define MEMORY_BUDGET_RENDERER (512 * MEMORY_KIB)
#define MEMORY_BUDGET_FONT_CPU (256 * MEMORY_KIB)
#define MEMORY_BUDGET_ARTWORK_STAGING (768 * MEMORY_KIB)
#define MEMORY_BUDGET_STARTUP (256 * MEMORY_KIB)

#define MEMORY_BUDGET_HEADLESS (MEMORY_BUDGET_CORE + MEMORY_BUDGET_PROTOCOL + \
    MEMORY_BUDGET_METADATA + MEMORY_BUDGET_HTTP + MEMORY_BUDGET_ENCRYPTED_BLOCKS + \
    MEMORY_BUDGET_DECODERS + MEMORY_BUDGET_DECODE_SCRATCH + MEMORY_BUDGET_PCM + \
    MEMORY_BUDGET_AUDIO_DEVICE)
#define MEMORY_BUDGET_GUI (MEMORY_BUDGET_CLAY_AND_FRAME + MEMORY_BUDGET_API_PAGES + \
    MEMORY_BUDGET_MODEL + MEMORY_BUDGET_UI_STATE + MEMORY_BUDGET_RENDERER + \
    MEMORY_BUDGET_FONT_CPU + MEMORY_BUDGET_ARTWORK_STAGING + MEMORY_BUDGET_STARTUP)
#define MEMORY_BUDGET_TOTAL (MEMORY_BUDGET_HEADLESS + MEMORY_BUDGET_GUI)

_Static_assert(MEMORY_BUDGET_HEADLESS == 2560 * MEMORY_KIB, "Headless ledger");
_Static_assert(MEMORY_BUDGET_GUI == 4864 * MEMORY_KIB, "GUI ledger");

#endif
